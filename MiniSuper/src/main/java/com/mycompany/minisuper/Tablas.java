    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:

        String cantidad = this.txtCant.getText();
        String descripcion = this.txtDescripcion.getText();
        String precio = this.txtPrecio.getText();

        if (cantidad.isBlank() || descripcion.isBlank() || precio.isBlank()) {

            JOptionPane.showMessageDialog(null, "Los valores son obligatorios", "Error!", 0);

            return;
        }

        //capturar la informacion de los textFields
        int castCantidad = Integer.parseInt(cantidad);
        double castPrecio = Double.parseDouble(precio);
        double subtotal = castCantidad * castPrecio;

        Object[] fila = {cantidad, descripcion, precio, subtotal};

        //mandarlo a la tabla
        if (isSaving) {
            this.model.addRow(fila);
        } else {
            //debo editar la tabla
            int filaSeleccionada = miTabla.getSelectedRow();

            model.setValueAt(castCantidad, filaSeleccionada, 0);
            model.setValueAt(descripcion, filaSeleccionada, 1);
            model.setValueAt(castPrecio, filaSeleccionada, 2);
            model.setValueAt(subtotal, filaSeleccionada, 3);

        }

        //limpiamos los datos de las cajas de texto
        limpiarDatos();

        //actualizar el total
        calcularTotal();


    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:

        //obtener la fila a eliminar
        int fila = miTabla.getSelectedRow(); // devuelve -1 si no se seleccionó ninguna fila

        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "debe seleccionar un producto");
            return;
        }

        String descripcion = model.getValueAt(fila, 1).toString();

        //hacer una confirmación
        int respuesta = JOptionPane.showConfirmDialog(this, String.format("Seguro que quiere eliminar el producto %s ?", descripcion));

        if (respuesta == 0) {
            model.removeRow(fila);
        }

    }//GEN-LAST:event_btnDeleteActionPerformed

    private void miTablaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_miTablaMouseClicked
        // TODO add your handling code here:

        int fila = miTabla.getSelectedRow(); // devuelve -1 si no se seleccionó ninguna fila

        String cantidad = model.getValueAt(fila, 0).toString();
        String descripcion = model.getValueAt(fila, 1).toString();
        String precio = model.getValueAt(fila, 2).toString();

        //rellenar las cajas de texto con la info obtenida
        txtCant.setText(cantidad);
        txtDescripcion.setText(descripcion);
        txtPrecio.setText(precio);

        this.isSaving = false; //porque ahora está editando

    }//GEN-LAST:event_miTablaMouseClicked

    void calcularTotal() {

        //recorrer todos los valores de la tabla (en subtotal)
        int totalRows = miTabla.getRowCount();//la cantidad de filas
        double total = 0;

        //recorrer todas las filas
        for (int fila = 0; fila < totalRows; fila++) {
            //sumarlos
            total += Double.parseDouble(model.getValueAt(fila, 3).toString());
        }

        //establecerlos en la etiqueta
        lblTotal.setText("L "+total);
    }

    void limpiarDatos() {

        txtCant.setText("");
        txtDescripcion.setText("");
        txtPrecio.setText("");
        this.isSaving = true;
        miTabla.clearSelection();

        //selecciona la caja de texto despues de limpiar los datos
        txtCant.grabFocus();

    }

