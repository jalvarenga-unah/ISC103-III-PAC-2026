    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:

        String cantidad = this.txtCant.getText();
        String descripcion = this.txtDescripcion.getText();
        String precio = this.txtPrecio.getText();

        if (cantidad.isBlank() || descripcion.isBlank() || precio.isBlank()) {

            JOptionPane.showMessageDialog(null, "Los valores son obligatorios", "Error!",0);

            return;
        }

        //capturar la informacion de los textFields
        int castCantidad = Integer.parseInt(cantidad);
        double castPrecio = Double.parseDouble(precio);
        double subtotal = castCantidad * castPrecio;

        Object[] fila = {cantidad, descripcion, precio, subtotal};

        //mandarlo a la tabla
        this.model.addRow(fila);

        //limpiamos los datos de las cajas de texto
        limpiarDatos();

    }//GEN-LAST:event_btnAddActionPerformed

    void limpiarDatos() {

        txtCant.setText("");
        txtDescripcion.setText("");
        txtPrecio.setText("");

    }

